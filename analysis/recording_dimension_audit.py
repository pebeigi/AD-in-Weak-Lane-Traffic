#!/usr/bin/env python3
"""Vehicle-dimension audit by recording, and paired tests within each recording.

The width column of recording 2 is about twice that of recording 1 for every
class, while lengths agree. SDPM uses widths in its lateral gap; RAU does not.
Recording 1 is therefore the subset on which the SDPM comparison does not
depend on the width column. This is a post hoc check on stored scores; no
model is rerun.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

from analysis.paired_statistics import METRICS, _boot_ci, _wilcoxon

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "outputs" / "results"
STAT = ROOT / "outputs" / "statistics"
CLASS_NAME = {0: "short", 1: "long", 2: "light"}


def dimensions() -> pd.DataFrame:
    df = pd.read_csv(
        ROOT / "Final_Lebanon_Data.csv",
        usecols=["id", "run_id", "lane_kf", "class", "length_smoothed", "width_smoothed"],
    )
    per_traj = (
        df.groupby(["run_id", "lane_kf", "id"])
        .agg(cls=("class", "first"), length=("length_smoothed", "median"), width=("width_smoothed", "median"))
        .reset_index()
    )
    out = (
        per_traj.groupby(["cls", "run_id"])
        .agg(n=("id", "size"), length_median=("length", "median"), width_median=("width", "median"),
             width_p10=("width", lambda w: w.quantile(0.1)), width_p90=("width", lambda w: w.quantile(0.9)))
        .reset_index()
    )
    out["class_name"] = out.cls.astype(int).map(CLASS_NAME)
    out.to_csv(STAT / "vehicle_dimensions_by_recording.csv", index=False)
    return out


def paired_by_recording() -> pd.DataFrame:
    df = pd.read_csv(RES / "paired_model_results.csv")
    rows = []
    for run, sub in df.groupby("run_id"):
        for key, _ in METRICS:
            a = sub[f"SDPM_holdout_{key}"].to_numpy(float)
            b = sub[f"RAU_holdout_{key}"].to_numpy(float)
            d = (b - a)[np.isfinite(b - a)]
            lo, hi = _boot_ci(d, np.median)
            p, rrb, _ = _wilcoxon(d)
            rows.append({
                "run_id": int(run), "metric": key, "n": len(d),
                "sdpm_median": float(np.median(a)), "rau_median": float(np.median(b)),
                "delta_median": float(np.median(d)), "ci95_low": lo, "ci95_high": hi,
                "p_wilcoxon": p, "rank_biserial": rrb,
                "n_rau_better": int((d < 0).sum()), "n_sdpm_better": int((d > 0).sum()),
            })
    out = pd.DataFrame(rows)
    out.to_csv(STAT / "paired_tests_by_recording.csv", index=False)
    return out


METRIC_TEX = {"ADE": "ADE", "RMSE_s": r"RMSE$_s$", "RMSE_d": r"RMSE$_d$",
              "RMSE_speed": r"RMSE$_v$", "FDE": "FDE"}
METRIC_KEY = {"ADE": "ADE", "RMSE_s": "RMSEs", "RMSE_d": "RMSEd", "RMSE_speed": "RMSEv", "FDE": "FDE"}
REC_KEY = {1: "One", 2: "Two"}


def signed(x: float, nd: int = 2) -> str:
    s = f"{abs(x):.{nd}f}"
    return (r"\ensuremath{-}" + s) if x < 0 and float(s) != 0 else s


def pfmt(p: float) -> str:
    return r"$<$0.001" if p < 0.001 else f"{p:.3f}"


def write_tex(paired: pd.DataFrame) -> None:
    paper = ROOT / "paper"
    lines, macros = [], {}
    for r in paired.itertuples():
        lines.append(
            f"{r.run_id} & {METRIC_TEX[r.metric]} & {r.sdpm_median:.2f} & {r.rau_median:.2f} & "
            f"{signed(r.delta_median)} [{signed(r.ci95_low)}, {signed(r.ci95_high)}] & "
            f"{pfmt(r.p_wilcoxon)} & {signed(r.rank_biserial)} & {r.n_rau_better} \\\\")
        tag = f"Byrec{REC_KEY[r.run_id]}{METRIC_KEY[r.metric]}"
        macros[tag + "Sdpm"] = f"{r.sdpm_median:.1f}"
        macros[tag + "Rau"] = f"{r.rau_median:.1f}"
        macros[tag + "D"] = signed(r.delta_median)
        macros[tag + "Dlo"] = signed(r.ci95_low)
        macros[tag + "Dhi"] = signed(r.ci95_high)
        macros[tag + "P"] = pfmt(r.p_wilcoxon)
        macros[tag + "Rrb"] = signed(r.rank_biserial)
        macros[tag + "NRau"] = str(r.n_rau_better)
        macros[tag + "NSdpm"] = str(r.n_sdpm_better)
    text = "\n".join(lines).replace("\n2 & ADE", "\n\\addlinespace\n2 & ADE", 1)
    (paper / "tables" / "tab_byrec.tex").write_text(text + "\n")
    body = "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in macros.items())
    (paper / "byrec_numbers.tex").write_text("% Generated by analysis/width_audit.py\n" + body)


SDPM_PARAMS = ["v0", "T", "s0", "a", "b", "s0_y", "s0_y_tilde", "lambda", "tau_lat"]


def calibration_by_recording() -> dict:
    """Training-window error and SDPM bound positions by recording."""
    res = pd.read_csv(RES / "paired_model_results.csv")
    bounds = pd.read_csv(STAT / "parameter_bound_position.csv")
    bounds = bounds[bounds.model == "SDPM"].set_index("parameter")
    z = pd.DataFrame({p: (res[f"SDPM_{p}"] - bounds.loc[p, "lower"])
                      / (bounds.loc[p, "upper"] - bounds.loc[p, "lower"]) for p in SDPM_PARAMS})
    out = {}
    for run in (1, 2):
        m = res.run_id == run
        key = REC_KEY[run]
        out[f"Byrec{key}SdpmTrainADE"] = f"{res.loc[m, 'SDPM_train_ADE'].median():.1f}"
        out[f"Byrec{key}RauTrainADE"] = f"{res.loc[m, 'RAU_train_ADE'].median():.1f}"
        out[f"Byrec{key}SdpmAnyBound"] = f"{((z[m] <= 0.05) | (z[m] >= 0.95)).any(axis=1).mean() * 100:.0f}"
        out[f"Byrec{key}SdpmSzeroyLo"] = f"{(z.loc[m, 's0_y'] <= 0.05).mean() * 100:.0f}"
        out[f"Byrec{key}SdpmLambdaLo"] = f"{(z.loc[m, 'lambda'] <= 0.05).mean() * 100:.0f}"
    pd.Series(out).to_csv(STAT / "calibration_by_recording.csv", header=["value"])
    return out


def write_dims(dims: pd.DataFrame) -> None:
    lines = []
    for cls, label in ((2, "Light (2)"), (1, "Long (1)"), (0, "Short (0)")):
        cells = [label]
        for run in (1, 2):
            r = dims[(dims.cls == cls) & (dims.run_id == run)].iloc[0]
            cells += [f"{int(r.n):,}", f"{r.length_median:.2f}",
                      f"{r.width_median:.2f} [{r.width_p10:.2f}, {r.width_p90:.2f}]"]
        lines.append(" & ".join(cells) + r" \\")
    (ROOT / "paper" / "tables" / "tab_dims.tex").write_text("\n".join(lines) + "\n")


def main() -> None:
    STAT.mkdir(parents=True, exist_ok=True)
    dims = dimensions()
    print(dims.round(2).to_string(index=False))
    write_dims(dims)
    paired = paired_by_recording()
    print(paired.round(3).to_string(index=False))
    write_tex(paired)
    extra = calibration_by_recording()
    print(extra)
    path = ROOT / "paper" / "byrec_numbers.tex"
    path.write_text(path.read_text() + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in extra.items()))


if __name__ == "__main__":
    main()
